def apply():
    """Puts the words into the catalog; returns how many tips changed."""
    from . import catalog
    n = 0
    for key, tip in REWORDS.items():
        cmd = catalog.BY_KEY.get(key)
        if cmd is not None and cmd.tip != tip:
            cmd.tip = tip
            n += 1
    return n
