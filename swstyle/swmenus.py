def _special_item(name, label):
    if name == "exit":
        return Item(label, True, lambda: Gui.getMainWindow().close(), None, _key_text("Std_Quit"))
    if name == "discard_sketch":
        s = _shell()
        watcher = getattr(s, "sketch_exit", None) if s is not None else None
        ready = watcher is not None and watcher.ready() is not None

        def run(watcher=watcher):
            from . import sketchexit
            sketchexit.discard(watcher, Gui.getMainWindow())
        return Item(label, ready, run)
    if name == "insert_spline_point":
        # a 3D sketch has its own Insert Spline Point; 2D sketches use the catalog's
        if _command("FreeWorks_Sketch3DInsertSplinePoint") is not None and _in_3d_sketch():
            return _command_item("FreeWorks_Sketch3DInsertSplinePoint", label)
        s = _shell()
        return _catalog_item(s, "InsertSplinePoint", label) if s is not None else None
    if name == "orientation":
        s = _shell()
        return _catalog_item(s, "ViewOrientation", label) if s is not None else None
    if name == "touch_mode":
        from . import uiextras
        return uiextras.touch_mode_item(label)
    if name == "task_pane":
        from . import uiextras
        on = uiextras.task_pane_shown() and uiextras._tasks_widget() is not None
        return Item(label, uiextras._tasks_widget() is not None,
                    lambda: uiextras.set_task_pane(not uiextras.task_pane_shown()), None, "", on)
    if name == "motion_manager":
        from . import uiextras
        return Item(label, True, lambda: uiextras.set_motion_manager(not uiextras.motion_manager_shown()), None, "",
                    uiextras.motion_manager_shown())
    return None


