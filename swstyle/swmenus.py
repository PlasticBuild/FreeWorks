def fill(menu, entries, shell):
    """Builds menu from entries. Returns the number of entries shown."""
    for old in menu.findChildren(QtWidgets.QMenu):
        if old.parent() is menu:
            old.deleteLater()
    menu.clear()
    shown = 0
    pending_separator = False
    for entry in when_entries(entries):
        r = resolve(shell, entry)
        if r is None:
            continue
        if r == S:
            pending_separator = shown > 0
            continue
        label, what = r
        if isinstance(what, Item):
            if pending_separator:
                menu.addSeparator()
                pending_separator = False
            _add_item(menu, _sw_dots(menu, what))
            shown += 1
            continue
        if isinstance(what, str) and what in INLINE:
            rows = _inline_special(what)
            if rows and pending_separator:
                menu.addSeparator()
                pending_separator = False
            for text, tip, run in rows:
                act = menu.addAction(text)
                act.setToolTip(tip)
                act.triggered.connect(lambda checked=False, run=run: _later(run))
                shown += 1
            continue
        sub = _new_menu(label, menu)
        if isinstance(what, str):
            ok = _fill_special(sub, what)
        else:
            ok = fill(sub, what, shell) > 0
        if not ok:
            sub.deleteLater()
            continue
        if pending_separator:
            menu.addSeparator()
            pending_separator = False
        menu.addMenu(sub)
        shown += 1
    return shown


