_PENDING_KEYS = {"at": 0.0, "by_command": {}}


def _pending_key(name):
    ""

    import time
    now = time.monotonic()
    if now - _PENDING_KEYS["at"] > 2.0:
        try:
            from . import keyfallback
            _PENDING_KEYS["by_command"] = {cmd: key for key, cmd in keyfallback.table().items()}
        except Exception:
            _PENDING_KEYS["by_command"] = {}
        _PENDING_KEYS["at"] = now
    key = _PENDING_KEYS["by_command"].get(name, "")
    return QtGui.QKeySequence(key).toString(QtGui.QKeySequence.NativeText) if key else ""


def _shown_key(name, key):
    ""
    if key or not name:
        return key
    try:    # repeatkey-1126: Enter/Tab/D/A live in key filters (filterkeys); show the key the user chose there
        from . import filterkeys
        if name in filterkeys.DEFAULTS:
            return filterkeys.shown(name)
    except Exception as e:
        _fw_log("swmenus.filterkey", e)
    key = _pending_key(name)
    if key:
        return key
    alias = KEY_ALIAS.get(name)
    if alias:
        key = _key_text(alias) or _pending_key(alias)
    if not key and name in SHEET_KEYS:
        key = QtGui.QKeySequence(SHEET_KEYS[name]).toString(QtGui.QKeySequence.NativeText)
    return key


def _label(text, key):
    if key == "Space":
        key = "SpaceBar"
    return text + ("\t" + key if key else "")


