def _command_item(name, label):
    if name == "Std_ViewScreenShot":
        item = _sheet_capture_item(label)
        if item is not None:
            return item
    command = _command(name)
    if command is None:
        return None
    action = _native_action(name)
    try:
        active = bool(command.isActive())
    except Exception:
        active = False
    if name in ONLY_WHEN_ACTIVE and not active:
        return None             # a pair (Record Video / Stop Video Record): only the one that applies shows
    if action is not None:
        active = active or action.isEnabled()
        checked = action.isChecked() if action.isCheckable() else None
        icon = action.icon()

        def run(action=action, name=name):
            if alive(action):
                action.trigger()
            else:
                Gui.runCommand(name, 0)
    else:
        from . import checkstate
        checked = checkstate.checked(name) if checkstate.known(name) else None
        icon = None
        try:
            pixmap = (command.getInfo() or {}).get("pixmap")
            icon = Gui.getIcon(pixmap) if _pixmap_known(pixmap) else None
        except Exception:
            icon = None

        def run(name=name):
            if not checkstate.run(name):        # a toggle runs the other way round, not always "off"
                Gui.runCommand(name, 0)
    try:        # extapps78: a part Insert command only the open sketch keeps back: on, closes the sketch first
        from . import featureflow
        if not active and featureflow.leaves_sketch(name):
            active, run = True, (lambda name=name: featureflow.run(name))
    except Exception as _fw_err:
        _fw_log("swmenus.py:leaves-sketch", _fw_err)
    if checked is None:
        from . import checkstate
        if checkstate.known(name):
            checked = checkstate.checked(name)
    from . import menunoicon, menurowart
    icon = _pack_icon(name, label) or menurowart.icon(name, label) or icon
    if menunoicon.none_for(name):
        icon = None
    if label in NOT_TOGGLES:
        checked = None
    if name in ("Std_Undo", "Std_Redo") and action is not None and action.text().strip():
        label = action.text().replace("&", "")      # fh257: the drawing Edit menu names the step too ("Undo Model View")
    item = Item(label or name, active, run, icon, _shown_key(name, _key_text(name, action)), checked)
    item.command = name           # Show command location finds the entry by it
    return item


