def when_entries(entries):
    """Splices ("when:<name>", (entries...)) groups in place, keeping the ones whose condition holds now."""
    out = []
    for e in entries:
        if isinstance(e, tuple) and len(e) == 2 and isinstance(e[0], str) and e[0].startswith("when:") and isinstance(e[1], (tuple, list)):
            if WHEN.get(e[0][5:], lambda: False)():
                out.extend(when_entries(e[1]))
        else:
            out.append(e)
    return out


def resolve(shell, entry):
    """(label, Item) or (label, [entries]) for a submenu or (label, special submenu name), or None."""
    if entry == S:
        return S
    if isinstance(entry, str):
        label, target = None, entry
    else:
        label, target = entry
    if isinstance(target, (tuple, list)):
        if label and label.replace("&", "") == "Sheet Metal":
            from . import smengine

            if not smengine.enabled():
                return None
        return label, target
    if target.startswith("fn:"):
        name = target[3:]
        if name in SUBMENUS:
            return label, name
        item = _special_item(name, label)
        return (label, item) if item is not None else None
    if target.startswith("cmd:"):
        item = None
        for name in target[4:].split("|"):        # "cmd:Ours|Fallback": the first command that exists
            item = _command_item(name, label)
            if item is not None:
                break
    else:
        if target in DRAWING_SWAP and drawing_in_front():
            target = DRAWING_SWAP[target]
        item = _catalog_item(shell, target, label)
        if target == "Sketch" and _editing_sketch(shell):

            leave = _catalog_item(shell, "ExitSketch", label or "Sketch")
            if leave is not None:
                item = Item(label or "Sketch", leave.enabled, leave.run, leave.icon, leave.key, True)
    return (item.label, item) if item is not None else None


