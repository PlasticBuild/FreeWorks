def _native_action(name):
    command = _command(name)
    if command is None:
        return None
    try:
        actions = [a for a in command.getAction() if isinstance(a, QtGui.QAction)]
    except Exception:
        actions = []
    return actions[0] if actions else None


def _key_text(name, action=None):
    if action is not None and alive(action):
        key = action.shortcut().toString(QtGui.QKeySequence.NativeText)
        if key:
            return key
    command = _command(name)
    try:
        key = command.getShortcut() if command is not None else ""
    except Exception:
        key = ""
    return QtGui.QKeySequence(key).toString(QtGui.QKeySequence.NativeText) if key else ""



