def hidden_natives():
    mw = Gui.getMainWindow()
    bar = mw.menuBar() if mw is not None else None
    if bar is None:
        return []
    # GitHub #3: PySide treats the menu QAction.menu() hands back as the action's child, and when that
    # action's wrapper goes (the loop moves on) the menu's wrapper is dropped with it, though the menu lives:
    # "Internal C++ object (QMenu) already deleted" on the next use. The actions are held while the menus are used.
    actions = list(bar.actions())
    _HELD_ACTIONS[:] = actions
    out = []
    for a in actions:
        m = a.menu()
        if m is not None and alive(m) and not _ours(m) and m.title().strip():
            out.append(m)
    return out


_HELD_ACTIONS = []


def _native_at(i, title):
    """FreeCAD's hidden menu number i when it still has that title, else the first one with it (None when gone)."""
    natives = hidden_natives()
    if i < len(natives) and alive(natives[i]) and natives[i].title() == title:
        return natives[i]
    return next((n for n in natives if alive(n) and n.title() == title), None)


def _actions_deep(menu, out, depth=0):
    if depth > 6 or not alive(menu):
        return
    for action in menu.actions():
        if action.isSeparator():
            continue
        out.append(action)
        if action.menu() is not None:
            _actions_deep(action.menu(), out, depth + 1)


def keep_keys(mw, natives):
    """Gives the main window every keyed action of the hidden FreeCAD menus: an action's key works
    only while a visible widget holds it. Returns the number of keyed actions now held."""
    actions = []
    for menu in natives:
        _actions_deep(menu, actions)
    held = set(mw.actions())
    count = 0
    for action in actions:
        if action.shortcut().isEmpty():
            continue
        if action not in held:
            mw.addAction(action)
        count += 1
    return count


_SPARE = {}       # objectName -> one of ours a workbench change took out of the bar
_PARK = []


def _parking():
    """A hidden widget outside the main window that holds the menus a workbench change left behind."""
    if not _PARK:
        holder = QtWidgets.QWidget()
        holder.setObjectName("SWLeftOutMenus")
        _PARK.append(holder)
    return _PARK[0]


class _BarWatch(QtCore.QObject):
    """FreeCAD rebuilds its menus on every workbench change (opening a part, assembly or drawing changes the
    workbench) and leaves the old ones behind under the menu bar, out of sight. Under the main window, every walk
    of its widgets or actions went through all of them, so a long session got slower and slower (Reviewer soak
    11-20: +20,000 menus, every round 3x slower after an hour). A menu taken out of the bar moves here to a hidden
    widget outside the main window, and back under the bar if it is put in again (FreeCAD moves its menus to the
    end that way). Done as the bar changes, with the menu the change names: FreeCAD still points into the old
    menus, so they are moved, never deleted (deleting them crashed FreeCAD), and nothing walks the bar's
    children (that met objects FreeCAD had deleted). Ours wait in _SPARE to go back in."""

    def eventFilter(self, obj, event):
        try:
            kind = event.type()
            if kind == QtCore.QEvent.Shortcut:
                return _alt_letter(obj, event)
            if kind not in (QtCore.QEvent.ActionRemoved, QtCore.QEvent.ActionAdded):
                return False
            action = event.action()
            menu = action.menu() if action is not None else None
            if menu is None:
                return False
            if kind == QtCore.QEvent.ActionAdded:
                if _ours(menu):
                    _watch_drop(menu)
                parent = menu.parent()
                if parent is not None and parent.objectName() == "SWLeftOutMenus":
                    menu.setParent(obj, menu.windowFlags())
                if _ours(menu) and _SPARE.get(menu.objectName()) is menu:
                    _SPARE.pop(menu.objectName(), None)
            elif not menu.isVisible() and menu.parent() is not None and menu.parent().objectName() != "SWLeftOutMenus":
                if _ours(menu):
                    _SPARE[menu.objectName()] = menu
                menu.setParent(_parking(), menu.windowFlags())
                if not _ours(menu):
                    _strip_later(menu)
        except Exception as _fw_err:
            _fw_log("swmenus.py:bar watch", _fw_err)
        return False


def _alt_letter(bar, event):
    ""


    try:
        seq = event.key()
    except Exception:
        return False
    for act in bar.actions():
        menu = act.menu()
        if menu is not None and act.isVisible() and _ours(menu) and QtGui.QKeySequence.mnemonic(act.text()) == seq:
            if not menu.isVisible():
                bar.setActiveAction(act)
            return True
    return False


class _Drop(QtCore.QObject):
    ""



    def eventFilter(self, menu, event):
        if event.type() == QtCore.QEvent.Show:
            try:
                _drop_under_strip(menu)
            except Exception as _fw_err:
                _fw_log("swmenus.py:drop", _fw_err)
        return False


_DROP = _Drop()


def _watch_drop(menu):
    if not menu.property("swDropWatch"):
        menu.installEventFilter(_DROP)
        menu.setProperty("swDropWatch", True)


def _drop_under_strip(menu):
    sh = _shell()
    qat = getattr(getattr(sh, "topbar", None), "qat", None) if sh is not None else None
    strip = getattr(qat, "menus", None)
    if strip is None or not alive(strip):
        return
    if not strip.isVisible():
        qat.show_menus()
    for b in getattr(strip, "_buttons", []):
        if alive(b) and b.menu() is menu and b.isVisible():
            where = b.mapToGlobal(QtCore.QPoint(0, b.height()))
            if menu.pos() != where:
                menu.move(where)
            return


_STRIP = []     # [menu, alive] of FreeCAD menus out of the bar, to empty once they stay out


def _strip_later(menu):
    """A FreeCAD menu left out of the bar still holds FreeCAD's shared command actions, so Qt tells it every time a
    command's state changes (ActionChanged): with hundreds of left-over menus that was 53,000 events a round on the
    bench and grew all session (Reviewer soak round 9b). Emptied 2 s later, once FreeCAD has not put it back."""
    cell = [menu, True]
    try:
        menu.destroyed.connect(lambda *_a, c=cell: c.__setitem__(1, False))
    except Exception:
        return
    _STRIP.append(cell)
    if len(_STRIP) == 1:
        QtCore.QTimer.singleShot(2000, _strip_pending)


def _strip(menu):
    """Takes every action out of menu and out of the menus under it (its own children only: a shared submenu, such
    as FreeCAD's Toolbars list, has no parent and is left alone). Removes only: nothing is deleted."""
    for m in [menu] + list(menu.findChildren(QtWidgets.QMenu)):
        for action in list(m.actions()):
            m.removeAction(action)


def _strip_pending():
    cells = list(_STRIP)
    del _STRIP[:]
    for menu, alive in cells:
        if not alive:
            continue
        try:
            parent = menu.parent()
            if parent is not None and parent.objectName() == "SWLeftOutMenus":
                _strip(menu)
                _FREE.append((time.monotonic(), menu))
        except Exception as _fw_err:
            _fw_log("swmenus.py:strip", _fw_err)
    if _FREE:
        QtCore.QTimer.singleShot(int(FREE_AFTER * 1000) + 1000, _free_pending)


# Emptied FreeCAD menus still out of the bar FREE_AFTER seconds later are deleted (pkg252): FreeCAD 1.1 makes a new set
# of menus on every workbench change and never deletes the old ones, so they piled up all session (Reviewer soak
# round 10: ~18 menus a workbench change, 25,000 widgets after an hour, 3 MB a round). Never inside the bar's
# ActionRemoved event (deleting there crashed FreeCAD): from a timer, long after FreeCAD let go of them, and only a
# menu still parked, hidden and with no actions left.
_FREE = []      # (time parked for good, menu)
FREE_AFTER = 10.0


def _free_pending():
    now = time.monotonic()
    keep = []
    import shiboken6
    for when, menu in _FREE:
        try:
            if not shiboken6.isValid(menu):
                continue
            if now - when < FREE_AFTER - 0.5:     # Qt may fire a timer up to 5% early
                keep.append((when, menu))
                continue
            parent = menu.parent()
            if parent is None or parent.objectName() != "SWLeftOutMenus" or menu.isVisible() or menu.actions():
                continue        # put back or used again: FreeCAD's, left alone
            if menu.findChildren(QtWidgets.QMenu):
                # fh239: an emptied menu still owns submenus FreeCAD keeps pointers to (View > Workbench: the
                # workbench list refills it whenever Preferences are applied); deleting it crashed FreeCAD there
                continue
            if QtWidgets.QApplication.activePopupWidget() is not None:
                keep.append((when, menu))       # a menu is open: wait
                continue
            # pkg261: through shiboken, not deleteLater: these menus are FreeCAD's (made in C++) and were
            # moved by setParent() from Python, so PySide kept their wrapper in the holder's child list
            # after a deleteLater (Reviewer soak: +64 QMenu and their QAction wrappers a round, never freed)
            shiboken6.delete(menu)
        except Exception as _fw_err:
            _fw_log("swmenus.py:free", _fw_err)
    _FREE[:] = keep
    if keep:
        QtCore.QTimer.singleShot(int(FREE_AFTER * 1000), _free_pending)


_WATCHER = []


def watch_bar(bar=None):
    """Puts _BarWatch on the menu bar (once per bar)."""
    if bar is None:
        mw = Gui.getMainWindow()
        bar = mw.menuBar() if mw is not None else None
        if bar is None:
            return None
    if bar.property("swBarWatch"):
        return _WATCHER[0] if _WATCHER else None
    if not _WATCHER:
        _WATCHER.append(_BarWatch())
    bar.installEventFilter(_WATCHER[0])
    bar.setProperty("swBarWatch", True)
    for act in bar.actions():       # menualt-1121: ours already in the bar
        if _ours(act.menu()):
            _watch_drop(act.menu())
    return _WATCHER[0]


def _left_out(bar, name):
    """Our menu called name that a workbench change took out of the bar: put back instead of a new one, which
    left a menu behind on every change."""
    return _SPARE.pop(name, None)


def _busy():
    """menubusy-1127: a file is opening or a document is rebuilding (File handling's recovery.busy())."""
    try:
        from . import recovery
        return bool(recovery.busy())
    except Exception:
        return False


def _bar_settled(bar):
    """menubusy-1127: our menus are in the bar and none of FreeCAD's own shows: nothing for _hook to do now."""
    mine = False
    for a in bar.actions():
        menu = a.menu()
        if menu is None:
            continue
        if _ours(menu):
            mine = True
        elif a.isVisible() and menu.objectName() != "&Windows":
            return False
    return mine


def _hook():
    try:
        mw = Gui.getMainWindow()
        if mw is None:
            return
        bar = mw.menuBar()
        if _busy() and _bar_settled(bar):
            return      # menubusy-1127: done on the first tick after the open or the rebuild (PERF-1127)
        watch_bar(bar)
        on = enabled() and _shell() is not None
        mine = {a.menu().objectName(): a for a in bar.actions() if a.menu() is not None
                and a.menu().objectName().startswith(PREFIX)}
        _extras(on)
        if not on:
            for a in mine.values():
                bar.removeAction(a)
            for a in bar.actions():
                if a.menu() is not None and not _ours(a.menu()) and a.menu().objectName() != "&Windows":
                    a.setVisible(True)
            return
        window = [a for a in bar.actions() if a.menu() is not None and a.menu().objectName() == WINDOW_MENU]
        if not window:
            # a workbench switch rebuilt the bar: put windowmenu.py's Window menu back now (its own timer may be
            # resting), or FreeCAD's Windows menu stays showing beside ours
            try:
                from . import windowmenu
                if windowmenu._watch is not None and windowmenu.enabled():
                    windowmenu._hook()
                    window = [a for a in bar.actions() if a.menu() is not None
                              and a.menu().objectName() == WINDOW_MENU]
            except Exception as error:
                App.Console.PrintLog("FreeCAD: Window menu: %s\n" % error)
        # FreeCAD's own menus out of sight, their keys kept
        for a in bar.actions():
            menu = a.menu()
            if menu is None or _ours(menu):
                continue
            if menu.objectName() == "&Windows" and not window:
                continue                # windowmenu.py is off: FreeCAD's Windows menu is the Window menu
            if a.isVisible():
                a.setVisible(False)
        keep_keys(mw, hidden_natives())
        # pkg261: mw.children(), not findChildren(): PySide kept every wrapper findChildren() handed out, also after
        # FreeCAD deleted the action (Reviewer soak: ~900 dead QAction wrappers an hour)
        count = sum(1 for o in mw.children() if isinstance(o, QtGui.QAction))
        global _actions_seen
        if count != _actions_seen:
            from . import swkeys
            swkeys.drop_sequences(mw)
            swkeys.drop_copies(mw)
            _actions_seen = count

        want = [PREFIX + t.replace("&", "") for t, _ in BEFORE_WINDOW]
        after = [PREFIX + t.replace("&", "") for t, _ in AFTER_WINDOW]
        for title, entries in MENUS:
            name = PREFIX + title.replace("&", "")
            if name not in mine:
                menu = _left_out(bar, name) or build_top(title, entries, bar)
                mine[name] = bar.addMenu(menu)

        hidden = set()
        if no_document():
            hidden = {PREFIX + x.replace("&", "") for x in NODOC_HIDDEN} | ({WINDOW_MENU} if window else set())
        for name, a in mine.items():
            if a.isVisible() == (name in hidden):
                a.setVisible(name not in hidden)
        if window and window[0].isVisible() == (WINDOW_MENU in hidden):
            window[0].setVisible(WINDOW_MENU not in hidden)
        visible = [a for a in bar.actions() if a.isVisible()]
        order = [n for n in want + ([WINDOW_MENU] if window else []) + after if n not in hidden]
        current = [a.menu().objectName() for a in visible if a.menu() is not None]
        if current[:len(order)] != order:
            for name in want + after:
                bar.removeAction(mine[name])
                mine[name].setVisible(name not in hidden)
            anchor = window[0] if window else None
            for name in want:
                if anchor is not None:
                    bar.insertAction(anchor, mine[name])
                else:
                    bar.addAction(mine[name])
            for name in after:
                bar.addAction(mine[name])
    except Exception as error:
        App.Console.PrintLog("FreeCAD: menus not set: %s\n" % error)


_extras_on = False


