class Item:
    """One resolved menu entry: what it shows and what it runs. None when nothing runs it."""

    def __init__(self, label, enabled, run, icon=None, key="", checked=None):
        self.label, self.enabled, self.run, self.icon, self.key, self.checked = label, enabled, run, icon, key, checked


def _pixmap_known(pixmap):
    """FreeCAD prints "Cannot find icon" for a picture of a workbench not loaded yet: ask first."""
    if not pixmap:
        return False
    import os
    if os.path.isfile(pixmap):
        return True
    return any(QtCore.QFile.exists(":/icons/%s%s" % (pixmap, ext)) for ext in (".svg", ".png", ".xpm", ""))


def _binding_icon(b, action):
    from . import icons
    if action is not None or (b.cmd.icon and icons.paints(icons.family(b.cmd.icon))):
        return b.icon()
    for own in (icons.family("FW_" + b.cmd.key), icons.drawn(b.cmd.key)):       # the pack's FW_<key>, else our drawn original (menus-icons-1119)
        if icons.paints(own):
            return own
    pixmap = (b.info or {}).get("pixmap")
    return b.icon() if _pixmap_known(pixmap) else None


def _as_is_shaded_edges(shell):
    """mbar-1126: View > Display ticks the mode in use; a new document is in FreeCAD's "As is" style."""
    try:
        from . import hlv
        if hlv.mode() is not None:
            return False
        return shell.draw_style_index() in (0, None)
    except Exception:
        return False


def _catalog_item(shell, key, label):
    from . import catalog
    if key not in catalog.BY_KEY:
        return None
    b = shell.binding(key)
    b.resolve()
    if not b.implemented:
        return None
    b.update_state()
    native = b.native
    action = b.action if b.action is not None and alive(b.action) else None
    # a toggle shows its tick box off as well as on (View > Hide/Show > Planes, Display > Zebra Stripes...)
    from . import checkstate
    toggle = (action is not None and action.isCheckable()) or bool(native and checkstate.known(native))
    checked = bool(b.checked) if toggle or b.checked else None
    if key == "ShadedEdges" and not checked and _as_is_shaded_edges(shell):
        checked = True
    if key in ("Undo", "Redo") and action is not None and action.text().strip():
        label = action.text().replace("&", "")         # undowording.py names the step: "Undo Extrude"
    item = Item(label or b.cmd.label, b.enabled, b.run, _binding_icon(b, action),
                _shown_key(native, _key_text(native, action) if native else "") or _shown_key(key, ""), checked)
    item.catkey = key       # tooltips-1126: rctips reads this entry's line (Cut > Revolve is not Freeshape Revolve)
    return item


_PACK = {}


def _pack_icon(name, label):
    ""

    try:
        from . import catalog, icons
        if not _PACK:
            for cmd in catalog._ALL:
                if not cmd.icon:
                    continue
                for native in cmd.natives:
                    _PACK.setdefault(("cmd", native), cmd.icon)
                _PACK.setdefault(("label", cmd.label.replace("&", "").rstrip(".")), cmd.icon)
            _PACK["ready"] = True
        clean = (label or "").replace("&", "").split("\t")[0].rstrip(".")
        for k in (("cmd", name), ("label", clean)):
            fam = _PACK.get(k)
            if fam:
                i = icons.family(fam)
                if icons.paints(i):
                    return i
    except Exception as _fw_err:
        _fw_log("swmenus.py:pack-icon", _fw_err)
    return None


