def _customized(menu, title):
    """Customize > Menus: an entry's new text and position (At Beginning, At End, Hidden), in the
    menu's submenus too, and the entries moved to another menu (Menu: on the Menus tab)."""
    try:
        from . import customizedlg
    except Exception:
        return
    target = getattr(customizedlg, "menu_target", None)

    def apply(act, label, key, over, menu_, first):
        text, position = over
        if text != label:
            act.setText(text + ("\t" + key if key else ""))
        if position == "Hidden":
            act.setVisible(False)
        elif position == "At Beginning" and first is not None and act is not first:
            menu_.removeAction(act)
            menu_.insertAction(first, act)
            return act
        elif position == "At End":
            menu_.removeAction(act)
            menu_.addAction(act)
        return first

    def walk(menu_, depth):
        first = menu_.actions()[0] if menu_.actions() else None
        for act in list(menu_.actions()):
            if act.isSeparator():
                continue
            label, _tab, key = act.text().replace("&", "").partition("\t")
            if target is not None and (target(title, label) or
                                       (customizedlg.menu_override(title, label) is None and target(title, _other_label(label)))):
                act.setVisible(False)           # moved to another menu: shown there
                continue
            over = customizedlg.menu_override(title, label)
            if over is None:
                over = customizedlg.menu_override(title, _other_label(label))
                if over is not None and over[0] == _other_label(label):
                    over = (label, over[1])     # the text was never changed: the row keeps its menu's dots
            if over is not None:
                first = apply(act, label, key, over, menu_, first)
            sub = act.menu()
            if sub is not None and depth < 4:
                walk(sub, depth + 1)
    walk(menu, 0)
    # entries moved here from another menu: built from that menu's entries, put at this menu's end
    moves = getattr(customizedlg, "moves_into", None)
    if moves is None:
        return
    for src, label in moves(title):
        entries = next((e for t, e in MENUS if t.replace("&", "") == src), None)
        if entries is None and hasattr(customizedlg, "others_key"):     # extapps89: Others / Macros commands
            key = customizedlg.others_key(src, label)
            entries = [key] if key else None
        if entries is None:
            continue
        tmp = QtWidgets.QMenu()
        try:
            fill(tmp, entries, _shell())
            found = []
            _find_action(tmp, label, found)
            if not found:
                _find_action(tmp, _other_label(label), found)
            if not found:
                continue
            owner, act = found[0]
            owner.removeAction(act)
            act.setParent(menu)
            sub = act.menu()
            if sub is not None:
                sub.setParent(menu, sub.windowFlags())
            act.setVisible(True)
            first = menu.actions()[0] if menu.actions() else None
            over = customizedlg.menu_override(src, label) or (label, "Default")
            label_, _tab, key = act.text().replace("&", "").partition("\t")
            menu.addAction(act)
            apply(act, label_, key, over, menu, first)
        finally:
            tmp.deleteLater()


