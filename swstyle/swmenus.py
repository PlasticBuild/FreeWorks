NO_DOCUMENT_HIDDEN = ("Edit", "Insert", "Window", "Help")


def _no_document_menus():
    ""
    try:
        show = App.ActiveDocument is not None
        for action in Gui.getMainWindow().menuBar().actions():
            if action.menu() is None or action.text().replace("&", "") not in NO_DOCUMENT_HIDDEN:
                continue
            if not show and action.isVisible():
                action.setProperty("swNoDocumentHidden", True)     # only the menus hidden here come back
                action.setVisible(False)
            elif show and action.property("swNoDocumentHidden"):
                action.setProperty("swNoDocumentHidden", False)
                action.setVisible(True)
    except Exception as _fw_err:
        _fw_log("swmenus.py:1450", _fw_err)


