_FW_SEEN = set()


def _fw_log(site, err):
    """Log a swallowed error once per place (Log level: invisible in the Report view at normal level)."""
    try:
        if site not in _FW_SEEN:
            _FW_SEEN.add(site)
            __import__("FreeCAD").Console.PrintLog("FreeCAD %s: %s\n" % (site, err))
    except Exception:
        return


import FreeCAD as App
import FreeCADGui as Gui
from PySide import QtCore

CMD = "FreeWorks_AutoGenerateDrawing"
LAST = {}            # what the last run made (checks): sheet size, views, dimensions, callouts, tables, balloons
ANSI_SERIES = ("A (ANSI) Landscape", "B (ANSI) Landscape", "C (ANSI) Landscape", "D (ANSI) Landscape",
               "E (ANSI) Landscape")
ISO_SERIES = ("A4 (ISO)", "A3 (ISO)", "A2 (ISO)", "A1 (ISO)", "A0 (ISO)")
SMALLEST_SCALE = 0.5   # the first sheet of the series whose fitted scale is 1:2 or larger


def _standard(doc=None):
    try:
        from . import paths
        return paths.params().GetString("DraftingStandard", "ISO")
    except Exception as _fw_err:
        _fw_log("drawauto.py:45", _fw_err)
        return "ISO"


def series():
    return ANSI_SERIES if _standard().upper().startswith("ANSI") else ISO_SERIES


def pick_sheet(page, shapes):
    """The sheet format of the series the views fit on (sets it on page). Returns its name."""
    from . import drawings as D
    from . import drawsheet as SH
    chosen = None
    for name in series():
        path = SH.size_path(name)
        if not path:
            continue
        SH.set_format(page, path)
        page.Document.recompute()
        chosen = name
        s = D.fit_scale(page, shapes)
        if s is not None and s >= SMALLEST_SCALE - 1e-9:
            break
    return chosen


def _is_assembly(doc):
    try:
        from . import asmcore
        return bool(asmcore.is_assembly(doc))
    except Exception as _fw_err:
        _fw_log("drawauto.py:76", _fw_err)
        return False


def auto_generate(source=None, path=None):
    """Make the drawing of source (the active part or assembly) with its views and annotations. Returns the
    drawing document, or None."""
    from . import drawings as D
    from . import newdoc
    source = source or newdoc.source_document()
    if source is None:
        return None
    LAST.clear()
    was = newdoc.ASK_SHEET_FORMAT
    newdoc.ASK_SHEET_FORMAT = False
    try:
        doc = D.make_drawing(source, path, palette=False, template="")
    finally:
        newdoc.ASK_SHEET_FORMAT = was
    if doc is None:
        return None
    page = next((o for o in doc.Objects if o.TypeId == "TechDraw::DrawPage"), None)
    if page is None:
        return doc
    asm = _is_assembly(source)
    shapes = D.model_shapes(source)
    doc.openTransaction("Auto-Generate Drawing")
    try:
        LAST["sheet"] = pick_sheet(page, shapes)
        try:
            D.sheet_defaults(page)
        except Exception as _fw_err:
            _fw_log("drawauto.py:105", _fw_err)
        front = D.standard_3_view(page, source)
        views = list(D.views_of(page))
        iso = _isometric(page, shapes, front)
        LAST["views"] = [v.Label for v in views] + ([iso.Label] if iso is not None else [])
        doc.recompute()
        _wait(views + ([iso] if iso else []))
        _fit_layout(page, views, iso)
        sec = None
        if not asm and front is not None:
            sec = _section(page, front, shapes, views + ([iso] if iso else []))
            if sec is not None:
                LAST["views"].append(sec.Label)
                _wait([sec])
        LAST["section"] = sec.Label if sec is not None else None
        if asm:
            _assembly_annotations(page, iso or front)
        else:
            _part_annotations(page, views)
    finally:
        doc.commitTransaction()
    doc.recompute()
    try:
        D.fit_page(page)
    except Exception as _fw_err:
        _fw_log("drawauto.py:130", _fw_err)
    return doc


def _isometric(page, shapes, front):
    """The Isometric view in the sheet's free corner (top right, under a revision table's place)."""
    from . import drawings as D
    if front is None:
        return None
    w, h = D.sheet_size(page)
    d, x = D.ORIENTATIONS["Isometric"]
    try:
        v = D.new_view(page, shapes, D._unit(d), D._unit(x), (w * 0.78, h * 0.66), float(page.Scale))
        D._name_orientation(v, "Isometric")
        return v
    except Exception as error:
        App.Console.PrintWarning("FreeCAD: Auto-Generate Drawing isometric: %s\n" % error)
        return None


def holes(shapes):
    """(centre, axis) of each round hole of shapes: a cylindrical face whose axis lies outside the solid."""
    out = []
    for o in shapes:
        sh = getattr(o, "Shape", o)
        for f in getattr(sh, "Faces", []):
            cyl = f.Surface
            if type(cyl).__name__ != "Cylinder":
                continue
            try:
                c = App.Vector(cyl.Center)
                a = App.Vector(cyl.Axis)
                u0, u1, v0, v1 = f.ParameterRange
                mid = f.valueAt((u0 + u1) / 2.0, (v0 + v1) / 2.0)
                n = mid - c
                c = c + a * a.dot(n)          # the axis point level with the face's middle
                if sh.isInside(c, 1e-6, False):
                    continue
            except Exception as _fw_err:
                _fw_log("drawauto.py:172", _fw_err)
                continue
            if not any((c - q).Length < 1e-6 and abs(a.dot(b)) > 0.999 for q, b in out):
                out.append((c, a))
    return out


def _sheet_point(view, p):
    """Model point -> the sheet point it is drawn at in view."""
    from . import drawings as D
    from . import drawviews as DV
    d, x, y = D.view_frame(view)
    c = DV.model_centre(view)
    x0, y0 = D.view_position(view)
    k = DV.view_scale(view)
    return x0 + k * (p - c).dot(x), y0 + k * (p - c).dot(y)


def _overlaps(a, b, gap):
    return not (a[2] + gap <= b[0] or b[2] + gap <= a[0] or a[3] + gap <= b[1] or b[3] + gap <= a[1])


MARGIN = 20.0          # clear of the sheet format's border and zone strip (ISO: 20 mm on the binding side)
GAP = 6.0


def _move(v, dx, dy):
    v.X = float(v.X) + dx
    v.Y = float(v.Y) + dy


def title_block(page):
    """(x0, y0, x1, y1) sheet mm of the title block, which views keep clear of; None when there is none."""
    try:
        from . import drawtitleblock as TB
        return TB.hotspot(page)
    except Exception as _fw_err:
        _fw_log("drawauto.py:209", _fw_err)
        return None


def _union(boxes):
    return (min(b[0] for b in boxes), min(b[1] for b in boxes), max(b[2] for b in boxes), max(b[3] for b in boxes))


def _free(r, w, h, blocked, gap=GAP):
    return (r[0] >= MARGIN and r[1] >= MARGIN and r[2] <= w - MARGIN and r[3] <= h - MARGIN and
            not any(b is not None and _overlaps(r, b, gap) for b in blocked))


def _place_union(u, w, h, tb):
    """(dx, dy) that puts box u on the sheet, inside the border and clear of the title block, moving it as little
    as it can; None when it does not fit."""
    cands = []
    xs = [0.0, MARGIN - u[0], w - MARGIN - u[2]]
    ys = [0.0, MARGIN - u[1], h - MARGIN - u[3]]
    if tb is not None:
        ys.append(tb[3] + GAP - u[1])          # above the title block
        xs.append(tb[0] - GAP - u[2])          # left of it
    for dx in xs:
        for dy in ys:
            r = (u[0] + dx, u[1] + dy, u[2] + dx, u[3] + dy)
            if _free(r, w, h, [tb]):
                cands.append((abs(dx) + abs(dy), dx, dy))
    if not cands:
        return None
    _c, dx, dy = min(cands)
    return dx, dy


def _fit_layout(page, views, iso):
    """The standard views moved together onto the sheet, inside its border and clear of the title block (the
    first angle Right view went off the left edge; on A4 the Top view sat on the title block); when they do not
    fit, the sheet scale steps down. The isometric view then goes to a free corner."""
    from . import drawviews as DV
    from . import drawings as D
    w, h = D.sheet_size(page)
    tb = title_block(page)
    views = [v for v in views if v is not None]
    if not views:
        return False
    moved = False
    for _try in range(4):
        u = _union([DV.view_box(v) for v in views])
        got = _place_union(u, w, h, tb)
        if got is not None:
            dx, dy = got
            if abs(dx) > 1e-6 or abs(dy) > 1e-6:
                for v in views:
                    _move(v, dx, dy)
                moved = True
            LAST["shifted"] = (round(dx, 2), round(dy, 2))
            break
        k = float(page.Scale)
        smaller = [s for s in D.STANDARD_SCALES if s < k - 1e-9]
        if not smaller:
            break
        page.Scale = smaller[0]                    # the views on the sheet scale follow
        LAST["scale"] = smaller[0]
        page.Document.recompute()
        for v in views + ([iso] if iso is not None else []):
            v.touch()
        page.Document.recompute()
        _wait(views + ([iso] if iso is not None else []))
    u = _union([DV.view_box(v) for v in views])
    if iso is None:
        return moved
    b = DV.view_box(iso)
    iw, ih = b[2] - b[0], b[3] - b[1]
    cx, cy = (b[0] + b[2]) / 2.0, (b[1] + b[3]) / 2.0
    if _free(b, w, h, [u, tb], 4.0):
        return moved
    for fx, fy in ((0.78, 0.70), (0.22, 0.70), (0.78, 0.30), (0.22, 0.30), (0.5, 0.82), (0.5, 0.2)):
        at = (min(max(w * fx, MARGIN + iw / 2.0), w - MARGIN - iw / 2.0),
              min(max(h * fy, MARGIN + ih / 2.0), h - MARGIN - ih / 2.0))
        r = (at[0] - iw / 2.0, at[1] - ih / 2.0, at[0] + iw / 2.0, at[1] + ih / 2.0)
        if _free(r, w, h, [u, tb], 4.0):
            _move(iso, at[0] - cx, at[1] - cy)
            LAST["iso_moved"] = True
            break
    else:
        _iso_anywhere(page, iso, u, tb, w, h)
    return True


def _iso_anywhere(page, iso, u, tb, w, h):
    """No corner is free for the isometric view: the free place nearest the top right corner, else the view
    at a smaller scale of its own (a standard step at a time) until it fits. Returns True when placed."""
    from . import drawings as D
    from . import drawviews as DV
    for _try in range(6):
        b = DV.view_box(iso)
        iw, ih = b[2] - b[0], b[3] - b[1]
        cx, cy = (b[0] + b[2]) / 2.0, (b[1] + b[3]) / 2.0
        if iw <= w - 2 * MARGIN and ih <= h - 2 * MARGIN:
            nx, ny = int((w - 2 * MARGIN - iw) // 5.0), int((h - 2 * MARGIN - ih) // 5.0)
            spots = [(MARGIN + iw / 2.0 + i * 5.0, MARGIN + ih / 2.0 + j * 5.0)
                     for i in range(nx + 1) for j in range(ny + 1)]
            spots.sort(key=lambda q: (q[0] - w * 0.78) ** 2 + (q[1] - h * 0.70) ** 2)
            for at in spots:
                r = (at[0] - iw / 2.0, at[1] - ih / 2.0, at[0] + iw / 2.0, at[1] + ih / 2.0)
                if _free(r, w, h, [u, tb], 4.0):
                    _move(iso, at[0] - cx, at[1] - cy)
                    LAST["iso_moved"] = True
                    return True
        k = DV.view_scale(iso)
        smaller = [q for q in D.STANDARD_SCALES if q < k - 1e-9]
        if not smaller:
            return False
        iso.ScaleType = "Custom"
        iso.Scale = smaller[0]
        LAST["iso_scale"] = smaller[0]
        iso.touch()
        page.Document.recompute()
        _wait_redrawn(iso, b)
    return False


def _wait_redrawn(view, before, seconds=20.0):
    """TechDraw draws a view again in the background: its old lines stay until then."""
    import time
    from . import drawviews as DV
    end = time.time() + seconds
    while time.time() < end:
        try:
            b = DV.view_box(view)
            if max(abs(p - q) for p, q in zip(b, before)) > 1e-3:
                return True
        except Exception as _fw_err:
            _fw_log("drawauto.py:wait_redrawn", _fw_err)
        try:
            from PySide import QtWidgets
            QtWidgets.QApplication.processEvents()
        except Exception as _fw_err:
            _fw_log("drawauto.py:wait_redrawn2", _fw_err)
        time.sleep(0.05)
    return False


def _section(page, front, shapes, views):
    ""

    from . import drawings as D
    from . import drawviews as DV
    found = holes(shapes)
    if not found:
        return None
    d, x, y = D.view_frame(front)
    box = D.model_box(shapes)
    if box is None:
        return None
    k = DV.view_scale(front)
    fb = DV.view_box(front)
    w, h = D.sheet_size(page)
    gap = max(12.0, 0.08 * min(w, h))
    margin = MARGIN
    taken = [DV.view_box(v) for v in views if v is not None] + [title_block(page)]

    def extent(axis):
        pts = [App.Vector(px, py, pz) for px in (box.XMin, box.XMax) for py in (box.YMin, box.YMax)
               for pz in (box.ZMin, box.ZMax)]
        vals = [p.dot(axis) for p in pts]
        return (max(vals) - min(vals)) * k

    def fits(r):
        return (r[0] >= margin and r[1] >= margin and r[2] <= w - margin and r[3] <= h - margin and
                not any(t is not None and _overlaps(r, t, gap * 0.5) for t in taken))

    for c, a in found:
        sx, sy = _sheet_point(front, c)
        if abs(a.dot(x)) < 0.5:           # a cut across the view's X shows the hole along its length
            kind = "Vertical"
            line = ((sx, fb[1] - 6.0), (sx, fb[3] + 6.0))
            sw, sh = extent(d), fb[3] - fb[1]
            cy = (fb[1] + fb[3]) / 2.0
            spots = [(fb[0] - gap - sw / 2.0, cy), (fb[2] + gap + sw / 2.0, cy)]
        else:
            kind = "Horizontal"
            line = ((fb[0] - 6.0, sy), (fb[2] + 6.0, sy))
            sw, sh = fb[2] - fb[0], extent(d)
            cx = (fb[0] + fb[2]) / 2.0
            spots = [(cx, fb[1] - gap - sh / 2.0), (cx, fb[3] + gap + sh / 2.0)]
        aligned = list(spots)
        grid = []                       # no room in line with the view: the free place nearest to it
        step = 5.0
        nx, ny = int(w // step), int(h // step)
        for i in range(nx + 1):
            for j in range(ny + 1):
                grid.append((i * step, j * step))
        grid.sort(key=lambda p: min((p[0] - a[0]) ** 2 + (p[1] - a[1]) ** 2 for a in aligned))
        for at in aligned + grid:
            r = (at[0] - sw / 2.0, at[1] - sh / 2.0, at[0] + sw / 2.0, at[1] + sh / 2.0)
            if fits(r):
                try:
                    sec = DV.make_section(page, front, kind, line, at)
                    if at not in aligned:
                        try:
                            from . import drawviewcmds as VC
                            VC.break_alignment(sec)
                        except Exception as _fw_err:
                            _fw_log("drawauto.py:351", _fw_err)
                        sec.X, sec.Y = at
                        page.Document.recompute()
                    return sec
                except Exception as error:
                    App.Console.PrintWarning("FreeCAD: Auto-Generate Drawing section: %s\n" % error)
                    return None
    return None


def _wait(views, seconds=30.0):
    """The views drawn (TechDraw draws them in the background) before annotations go on them."""
    import time
    end = time.time() + seconds
    while time.time() < end:
        try:
            if all(len(v.getVisibleEdges()) for v in views if v is not None):
                return True
        except Exception as _fw_err:
            _fw_log("drawauto.py:370", _fw_err)
        try:
            from PySide import QtWidgets
            QtWidgets.QApplication.processEvents()
        except Exception as _fw_err:
            _fw_log("drawauto.py:375", _fw_err)
        time.sleep(0.05)
    return False


def _part_annotations(page, views):
    from . import drawannot as DA
    try:
        dims = DA.model_items(page, views)
        LAST["dimensions"] = len(dims or [])
    except Exception as error:
        LAST["dimensions"] = 0
        App.Console.PrintWarning("FreeCAD: Auto-Generate Drawing dimensions: %s\n" % error)
    try:
        calls = DA.hole_callouts(page, views)
        LAST["callouts"] = len(calls or [])
    except Exception as error:
        calls = []
        LAST["callouts"] = 0
        App.Console.PrintWarning("FreeCAD: Auto-Generate Drawing hole callouts: %s\n" % error)
    LAST["replaced"] = _drop_hole_diameters(page, calls or [])


def _radius_of(dim):
    from . import drawannot as DA
    try:
        view, subs = dim.References2D[0][0], list(dim.References2D[0][1])
        i = int(subs[0][4:]) if subs and subs[0].startswith("Edge") else None
        return next((r for j, _c, r in DA.circles(view) if j == i), None) if i is not None else None
    except Exception as _fw_err:
        _fw_log("drawauto.py:466", _fw_err)
        return None


def _drop_hole_diameters(page, calls):
    ""

    sizes = [r for r in (_radius_of(c) for c in calls) if r is not None]
    if not sizes:
        return 0
    gone = 0
    doc = page.Document
    for o in list(page.Views):
        if o.TypeId != "TechDraw::DrawViewDimension" or getattr(o, "SWHoleCallout", False):
            continue
        if o.Type not in ("Diameter", "Radius"):
            continue
        r = _radius_of(o)
        if r is not None and any(abs(r - q) < 1e-6 for q in sizes):
            try:
                doc.removeObject(o.Name)
                gone += 1
            except Exception as _fw_err:
                _fw_log("drawauto.py:427", _fw_err)
    return gone


def _assembly_annotations(page, view):
    from . import drawannot as DA
    from . import drawtables as DT
    try:
        bom = DT.make_bom(page, view, DT.anchor(page, "BOM"))
        DT.attach(bom)
        LAST["bom"] = bom.Name
    except Exception as error:
        App.Console.PrintWarning("FreeCAD: Auto-Generate Drawing BOM: %s\n" % error)
    page.Document.recompute()
    try:
        balloons = DA.auto_balloon(page, view)
        LAST["balloons"] = len(balloons or [])
    except Exception as error:
        LAST["balloons"] = 0
        App.Console.PrintWarning("FreeCAD: Auto-Generate Drawing balloons: %s\n" % error)
    try:
        rev = DT.make_revision_table(page)
        LAST["revision"] = rev.Name
    except Exception as error:
        App.Console.PrintWarning("FreeCAD: Auto-Generate Drawing revision table: %s\n" % error)


class _Command:
    def GetResources(self):
        from . import drawings as D
        return {"MenuText": "Auto-Generate Drawing", "Pixmap": D.pixmap("TechDraw_PageDefault"),
                "ToolTip": "Makes the drawing of the active part or assembly with its views, dimensions and hole "
                           "callouts (an assembly: BOM, balloons and a revision table)."}

    def IsActive(self):
        try:
            from . import newdoc
            return newdoc.source_document() is not None
        except Exception:
            return False

    def Activated(self):
        QtCore.QTimer.singleShot(0, lambda: auto_generate())


def register():
    if CMD not in Gui.listCommands():
        Gui.addCommand(CMD, _Command())
