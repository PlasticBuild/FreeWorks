def _ansi():
    t = {}
    rows = []
    for a, ts in ANGLE_LEGS.items():
        for th in ts:
            rows.append(("%s x %s x %s" % (_g(a), _g(a), _g(th)), a, a, th))
    for a, b in UNEQUAL_ANGLES:
        for th in UNEQUAL_T:
            rows.append(("%s x %s x %s" % (_g(a), _g(b), _g(th)), a, b, th))
    t["angle iron"] = {"fillet": True, "sizes": [
        (n,) + _inch(b, a, th, 0, th, th / 2) + (_w((a + b - th) * th * IN * IN),) for n, a, b, th in rows]}
    t["c channel"] = {"fillet": True, "sizes": [
        (n,) + _inch(d, bf, tw, tf, tf, tf / 2) + (round(float(n.split(" x ")[1]) * LB_FT, 2),)
        for n, d, bf, tw, tf in C_SHAPES]}
    rows = [("%s x %s x %s" % (_g(a), _g(b), _g(th)), a, b, th) for a, b, ts in RECT_HSS for th in ts]
    t["rectangular tube"] = {"fillet": True, "sizes": [
        (n,) + _inch(b, a, th, 0, 2 * th, th) + (_w(2 * (a + b - 2 * th) * th * IN * IN),) for n, a, b, th in rows]}
    rows = [("%s x %s x %s" % (_g(a), _g(a), _g(th)), a, th) for a, ts in SQUARE_HSS for th in ts]
    t["square tube"] = {"fillet": True, "sizes": [
        (n,) + _inch(a, a, th, 0, 2 * th, th) + (_w(4 * (a - th) * th * IN * IN),) for n, a, th in rows]}
    rows = [("%s sch %d" % (n, sch), od, th) for n, od, t40, t80 in PIPES for sch, th in ((40, t40), (80, t80))]
    t["pipe"] = {"fillet": False, "sizes": [
        (n,) + _inch(od, od, th, 0, 0, 0) + (_w(3.14159265 * (od - th) * th * IN * IN),) for n, od, th in rows]}
    t["s section"] = {"fillet": True, "sizes": [
        (n,) + _inch(bf, d, tw, tf, tw, tf * 0.4) + (round(float(n.split(" x ")[1]) * LB_FT, 2),)
        for n, d, bf, tw, tf in S_SHAPES]}
    t["sb beam"] = {"fillet": True, "sizes": [
        (n,) + _inch(bf, d, tw, tf, max(tw, 0.6 * tf), 0) + (round(float(n.split(" x ")[1]) * LB_FT, 2),)
        for n, d, bf, tw, tf in W_SHAPES]}
    return t


